export const buildFallbackEmbassyRecord = (hostCountry, nationalityCountry) => {
  const hostLabel = embassyHostCity[hostCountry.name] || hostCountry.name;
  const fallbackSource = nationalityEmbassyFallbacks[nationalityCountry.name] || {};
  return {
    name: `سفارة ${nationalityCountry.name} - ${hostLabel}`,
    nameEn: `${countryNamesEn[nationalityCountry.name] || nationalityCountry.name} Embassy - ${countryNamesEn[hostCountry.name] || hostCountry.name}`,
    address: `${hostLabel} - ${hostCountry.name}`,
    note: fallbackSource.note || "سيتم تحديث بيانات التواصل التفصيلية قريبًا.",
    noteEn: fallbackSource.noteEn || "Detailed contact information will be updated soon.",
    phone: fallbackSource.phone || "",
    website: fallbackSource.website || "",
    email: fallbackSource.email || "",
  };
};

export const buildEmbassyDirectory = () => {
  const directory = {};

  countriesData.forEach((hostCountry) => {
    directory[hostCountry.name] = countriesData
      .filter((nationalityCountry) => nationalityCountry.name !== hostCountry.name)
      .map((nationalityCountry) => {
        let embassyRecord;

        if (hostedEmbassyOverrides[hostCountry.name]?.[nationalityCountry.name]) {
          embassyRecord = hostedEmbassyOverrides[hostCountry.name][nationalityCountry.name];
        } else if (nationalityCountry.name === "مصر" && hostCountry.officialContacts?.embassy) {
          embassyRecord = hostCountry.officialContacts.embassy;
        } else {
          embassyRecord = buildFallbackEmbassyRecord(hostCountry, nationalityCountry);
        }

        return {
          name: nationalityCountry.name,
          nameEn: countryNamesEn[nationalityCountry.name] || nationalityCountry.name,
          nationality: nationalityCountry.name,
          hostCountry: hostCountry.name,
          flag: nationalityCountry.flag,
          flagImg: nationalityCountry.flagImg,
          officialContacts: {
            embassy: {
              phone: "",
              website: "",
              email: "",
              whatsapp: "",
              facebook: "",
              ...embassyRecord,
            },
          },
        };
      });
  });

  return directory;
};

export const embassyDirectory = buildEmbassyDirectory();
